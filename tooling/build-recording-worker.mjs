import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const directory = new URL(
  "../packages/core/src/lib/recording/",
  import.meta.url,
);
const result = await build({
  stdin: {
    contents:
      "import { recordingWorker } from './worker.ts'; recordingWorker();",
    resolveDir: fileURLToPath(directory),
  },
  bundle: true,
  platform: "browser",
  format: "iife",
  target: "es2022",
  minify: true,
  write: false,
  logLevel: "silent",
});
const content = `// Generated by tooling/build-recording-worker.mjs; do not edit.\nexport const workerSource: string = ${JSON.stringify(result.outputFiles[0].text)};\n`;
const destination = new URL("worker-source.ts", directory);
if (process.argv.includes("--check")) {
  if ((await readFile(destination, "utf8")) !== content)
    throw new Error(
      "Stale recording worker; run node tooling/build-recording-worker.mjs",
    );
} else await writeFile(destination, content);
process.stdout.write(
  `recording worker: ${result.outputFiles[0].text.length} bytes; self-contained script\n`,
);
