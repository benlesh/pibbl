import { createHash } from "node:crypto";
import { readFile, writeFile, mkdtemp, rm } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
const root = new URL("../packages/core/", import.meta.url);
const sources = [
  "Cargo.toml",
  "Cargo.lock",
  "rust-toolchain.toml",
  "src/lib.rs",
];
const hash = createHash("sha256");
for (const source of sources)
  hash.update(await readFile(new URL(`wasm/recording/${source}`, root)));
const sourceHash = hash.digest("hex");
const destination = new URL("src/lib/recording/wasm-bytes.ts", root);
if (process.argv.includes("--check")) {
  const content = await readFile(destination, "utf8");
  if (!content.includes(`// Source SHA256: ${sourceHash}\n`))
    throw new Error(
      "Stale recording WASM; run node tooling/build-recording-wasm.mjs",
    );
  const bytes = Buffer.from(
    JSON.parse(content.match(/export const bytes = (.+);/)[1]),
    "base64",
  );
  const binaryHash = createHash("sha256").update(bytes).digest("hex");
  if (!content.includes(`// WASM SHA256: ${binaryHash}\n`))
    throw new Error("Recording WASM integrity check failed.");
  const module = new WebAssembly.Module(bytes);
  if (WebAssembly.Module.imports(module).length)
    throw new Error("Recording WASM must be self-contained.");
  process.stdout.write(
    `recording: ${bytes.length} bytes; source fingerprint and WASM validated\n`,
  );
} else {
  const temporary = await mkdtemp(join(tmpdir(), "pibbl-recording-build-"));
  try {
    const result = spawnSync(
      process.env.PIBBL_CARGO ?? "cargo",
      [
        "build",
        "--manifest-path",
        fileURLToPath(new URL("wasm/recording/Cargo.toml", root)),
        "--locked",
        "--release",
        "--target",
        "wasm32-unknown-unknown",
        "--target-dir",
        temporary,
      ],
      {
        stdio: "inherit",
        cwd: fileURLToPath(new URL("wasm/recording/", root)),
      },
    );
    if (result.status !== 0)
      throw new Error(
        "Failed compiling recording WASM. Install the pinned Rust toolchain and wasm32 target.",
      );
    const bytes = await readFile(
      join(temporary, "wasm32-unknown-unknown/release/pibbl_recording.wasm"),
    );
    await writeFile(
      destination,
      `// Generated by tooling/build-recording-wasm.mjs; do not edit.\n// Source SHA256: ${sourceHash}\n// WASM SHA256: ${createHash("sha256").update(bytes).digest("hex")}\nexport const bytes = ${JSON.stringify(bytes.toString("base64"))};\n`,
    );
    process.stdout.write(`recording: ${bytes.length} bytes\n`);
  } finally {
    await rm(temporary, { recursive: true, force: true });
  }
}
