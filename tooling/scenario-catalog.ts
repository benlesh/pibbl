import {
  getLearningExampleRoute,
  getScenarioRoute,
  learningExampleCatalog,
  learningSections,
  loadLearningExample,
  loadScenario,
  scenarioCatalog,
  scenarioCatalogIndex,
  validateLearningExampleCatalog,
  validateScenarioCatalog,
} from '@crc/scenarios';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { relative, resolve } from 'node:path';
import { format } from 'prettier';

const workspaceRoot = process.cwd();
const scenarioDirectory = resolve(workspaceRoot, 'packages/scenarios/src');
const indexPath = resolve(workspaceRoot, 'docs/scenario-index.md');

function displayList(values: readonly string[]): string {
  return values.length ? values.join(', ') : '(none)';
}

function escapeCell(value: string): string {
  return value.replaceAll('|', '\\|');
}

function scenarioLink(id: string, title: string): string {
  return `[${title}](#${id})`;
}

function renderGroups(
  groups: typeof scenarioCatalogIndex.byApi,
): string[] {
  return groups.map(group => {
    const links = group.scenarios.map(entry =>
      scenarioLink(entry.metadata.id, entry.metadata.title)
    );
    return `- **${group.label}:** ${links.join(', ')}`;
  });
}

function renderIndex(): string {
  const lines = [
    '# CRC example catalogs',
    '',
    '<!-- Generated by `pnpm scenarios:write-index`; do not edit by hand. -->',
    '',
    `The learner studio contains ${learningExampleCatalog.length} focused lessons. A separate automated-testing catalog preserves ${scenarioCatalog.length} deterministic browser fixtures.`,
    '',
    'Learning sources use one clean `mount(canvas)` contract and are both displayed and executed by the studio. Test fixtures retain their diagnostic metadata, actions, and exact headless-browser source.',
    '',
    '## Learning studio',
    '',
    '| Order | Lesson | Section | Public API | Studio route | Canonical source |',
    '| ---: | --- | --- | --- | --- | --- |',
  ];

  for (const entry of learningExampleCatalog) {
    const section = learningSections.find(value => value.id === entry.section);
    const sourceLink = `../${entry.source.path}`;
    lines.push(
      `| ${entry.order} | <a id="lesson-${entry.slug}"></a>**${escapeCell(entry.title)}**<br>${escapeCell(entry.summary)} | ${section?.label ?? entry.section} | ${escapeCell(entry.api.join(', '))} | \`${getLearningExampleRoute(entry)}\` | [\`${entry.source.path}\`](${sourceLink}) |`,
    );
  }

  lines.push(
    '',
    '## Automated test labs',
    '',
    'These fixtures are deterministic evidence for browser verification. Their visibility, maturity, action IDs, diagnostics, and manual procedures are intentionally test-oriented.',
    '',
    '| Order | Scenario | Category | Visibility / maturity | Lab route | Executable source |',
    '| ---: | --- | --- | --- | --- | --- |',
  );

  for (const entry of scenarioCatalogIndex.learningPath) {
    const metadata = entry.metadata;
    const sourceLink = `../${entry.source.path}`;
    lines.push(
      `| ${metadata.learningOrder} | <a id="${metadata.id}"></a>**${escapeCell(metadata.title)}**<br>${escapeCell(metadata.summary)} | ${escapeCell(metadata.category)} | ${metadata.visibility} / ${metadata.maturity} | \`${getScenarioRoute(entry)}\` | [\`${entry.source.path}\`](${sourceLink}) |`,
    );
  }

  lines.push(
    '',
    '## Test labs by public API',
    '',
    ...renderGroups(scenarioCatalogIndex.byApi),
    '',
    '## By concept',
    '',
    ...renderGroups(scenarioCatalogIndex.byConcept),
    '',
    '## By category',
    '',
    ...renderGroups(scenarioCatalogIndex.byCategory),
    '',
    '## By visibility and maturity',
    '',
    ...renderGroups(scenarioCatalogIndex.byVisibilityAndMaturity),
    '',
  );
  return `${lines.join('\n')}\n`;
}

async function validateSources(): Promise<void> {
  validateScenarioCatalog(scenarioCatalog);
  validateLearningExampleCatalog(learningExampleCatalog);
  const discoveredPaths = (await readdir(scenarioDirectory, { recursive: true }))
    .filter(name => /\.example\.tsx?$/u.test(name))
    .map(name => `packages/scenarios/src/${name.replaceAll('\\', '/')}`)
    .sort();
  const learningPaths = discoveredPaths.filter(path => path.includes('/learning/'));
  const testPaths = discoveredPaths.filter(path => !path.includes('/learning/'));
  const catalogPaths = scenarioCatalog.map(entry => entry.source.path).sort();
  if (testPaths.join('\n') !== catalogPaths.join('\n')) {
    const catalogSet = new Set(catalogPaths);
    const discoveredSet = new Set(testPaths);
    const omitted = testPaths.filter(path => !catalogSet.has(path));
    const missing = catalogPaths.filter(path => !discoveredSet.has(path));
    throw new Error(
      `Scenario source discovery disagrees with the catalog. Omitted: ${displayList(omitted)}. Missing: ${displayList(missing)}.`,
    );
  }

  const learningCatalogPaths = learningExampleCatalog.map(entry => entry.source.path).sort();
  if (learningPaths.join('\n') !== learningCatalogPaths.join('\n')) {
    const catalogSet = new Set(learningCatalogPaths);
    const discoveredSet = new Set(learningPaths);
    const omitted = learningPaths.filter(path => !catalogSet.has(path));
    const missing = learningCatalogPaths.filter(path => !discoveredSet.has(path));
    throw new Error(
      `Learning source discovery disagrees with the catalog. Omitted: ${displayList(omitted)}. Missing: ${displayList(missing)}.`,
    );
  }

  for (const entry of scenarioCatalog) {
    const sourceText = await readFile(resolve(workspaceRoot, entry.source.path), 'utf8');
    if (!sourceText.includes(entry.source.marker)) {
      throw new Error(
        `Scenario "${entry.metadata.id}" source is missing marker "${entry.source.marker}".`,
      );
    }
    const definition = await loadScenario(entry);
    if (entry.metadata.visibility === 'documentation-candidate') {
      if (!sourceText.includes("from '@crc/core'")) {
        throw new Error(
          `Documentation candidate "${entry.metadata.id}" must show direct public @crc/core usage.`,
        );
      }
      if (/\b(?:describe|expect|it|test)\s*\(/u.test(sourceText) || sourceText.includes('vitest')) {
        throw new Error(
          `Documentation candidate "${entry.metadata.id}" contains test-runner diagnostics.`,
        );
      }
    }
    if (definition.actionIds.length !== entry.actions.length) {
      throw new Error(`Scenario "${entry.metadata.id}" has unreadable action metadata.`);
    }
  }

  for (const entry of learningExampleCatalog) {
    const sourceText = await readFile(resolve(workspaceRoot, entry.source.path), 'utf8');
    const imports = [...sourceText.matchAll(/from\s+['"]([^'"]+)['"]/gu)].map(match => match[1]);
    if (!imports.length || imports.some(moduleName => moduleName !== '@crc/core')) {
      throw new Error(`Learning example "${entry.slug}" may import only from @crc/core.`);
    }
    if (!/export\s+default\s+function\s+mount\s*\(canvas:\s*HTMLCanvasElement\)\s*:\s*CRCController/gu.test(sourceText)) {
      throw new Error(`Learning example "${entry.slug}" must export the canonical mount(canvas) contract.`);
    }
    if (/SOURCE_ID|\b(?:describe|expect|it|test)\s*\(|vitest/gu.test(sourceText)) {
      throw new Error(`Learning example "${entry.slug}" contains test or source-marker scaffolding.`);
    }
    await loadLearningExample(entry);
  }
}

await validateSources();
const generatedIndex = await format(renderIndex(), { parser: 'markdown' });
if (process.argv.includes('--write')) {
  await writeFile(indexPath, generatedIndex, 'utf8');
  process.stdout.write(
    `Wrote ${relative(workspaceRoot, indexPath)} for ${learningExampleCatalog.length} lessons and ${scenarioCatalog.length} test labs.\n`,
  );
} else {
  const existingIndex = await readFile(indexPath, 'utf8').catch(() => '');
  if (existingIndex.replaceAll('\r\n', '\n') !== generatedIndex) {
    throw new Error('docs/scenario-index.md is stale. Run `pnpm scenarios:write-index`.');
  }
  process.stdout.write(
    `Validated ${learningExampleCatalog.length} lessons, ${scenarioCatalog.length} test labs, and docs/scenario-index.md.\n`,
  );
}
