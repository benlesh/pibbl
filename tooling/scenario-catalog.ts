import {
  getLearningExampleRoute,
  getScenarioRoute,
  learningExampleCatalog,
  loadLearningExample,
  loadScenario,
  loadTutorialSnapshot,
  scenarioCatalog,
  scenarioCatalogIndex,
  validateLearningExampleCatalog,
  validateScenarioCatalog,
  validateTutorialSnapshotCatalog,
  tutorialSnapshotCatalog,
} from '@pibbl/scenarios';
import { readFile, writeFile } from 'node:fs/promises';
import { relative, resolve } from 'node:path';
import { format } from 'prettier';
import {
  validateDiagramEditorTutorialSourceText,
  validateLearningSourceText,
  validateScenarioSourceText,
} from './learning-source-contract';
import {
  assertExampleSourceDiscovery,
  discoverExampleSourcePaths,
} from './scenario-source-discovery';

const workspaceRoot = process.cwd();
const scenarioDirectory = resolve(workspaceRoot, 'packages/scenarios/src');
const indexPath = resolve(workspaceRoot, 'docs/scenario-index.md');

function escapeCell(value: string): string {
  return value.replaceAll('|', '\\|');
}

function publicLocation(entry: (typeof learningExampleCatalog)[number]): string {
  switch (entry.browseGroup) {
    case 'drawing':
      return 'Drawing';
    case 'composition':
      return 'Composition';
    case 'three':
      return 'Three.js';
    case 'layout':
      return 'Layout';
    case 'events-and-interaction':
      return 'Events and interaction';
    case 'focus-and-keyboard':
      return 'Focus and keyboard';
    default:
      return 'Learn';
  }
}

function scenarioLink(id: string, title: string): string {
  return `[${title}](#${id})`;
}

function tutorialRouteSuffix(sourcePath: string): string {
  const basename = sourcePath.split('/').at(-1);
  if (!basename) throw new Error(`Tutorial source path "${sourcePath}" has no basename.`);
  return basename.replace(/^\d{2}-/u, '').replace(/\.example\.tsx$/u, '');
}

function renderGroups(
  groups: typeof scenarioCatalogIndex.byApi,
): string[] {
  return groups.map(group => {
    const links = group.scenarios.map(entry =>
      scenarioLink(entry.metadata.id, entry.metadata.title)
    );
    return `- **${group.label}:** ${links.join(', ')}`;
  });
}

function renderIndex(): string {
  const lines = [
    '# Pibbl example catalogs',
    '',
    '<!-- Generated by `pnpm scenarios:write-index`; do not edit by hand. -->',
    '',
    `The learner studio contains ${learningExampleCatalog.length} focused lessons and ${tutorialSnapshotCatalog.length} tutorial snapshots. A separate automated-testing catalog preserves ${scenarioCatalog.length} deterministic browser fixtures.`,
    '',
    'Learning sources use one clean `mount(canvas)` contract and are both displayed and executed by the studio. Test fixtures retain their diagnostic metadata, actions, and exact headless-browser source.',
    '',
    '## Learning studio',
    '',
    '| Order | Lesson | Public location | Public API | Studio route | Canonical source |',
    '| ---: | --- | --- | --- | --- | --- |',
  ];

  for (const entry of learningExampleCatalog) {
    const sourceLink = `../${entry.source.path}`;
    lines.push(
      `| ${entry.order} | <a id="lesson-${entry.slug}"></a>**${escapeCell(entry.title)}**<br>${escapeCell(entry.summary)} | ${publicLocation(entry)} | ${escapeCell(entry.api.join(', '))} | \`${getLearningExampleRoute(entry)}\` | [\`${entry.source.path}\`](${sourceLink}) |`,
    );
  }

  lines.push(
    '',
    '## Tutorial snapshots',
    '',
    '| Chapter | Snapshot | Route | Canonical source |',
    '| ---: | --- | --- | --- |',
  );

  for (const entry of tutorialSnapshotCatalog) {
    const sourceLink = `../${entry.source.path}`;
    const route = `#/learn/tutorials/${entry.tutorial}/${tutorialRouteSuffix(entry.source.path)}`;
    lines.push(
      `| ${entry.chapter} | **${escapeCell(entry.title)}** | \`${route}\` | [\`${entry.source.path}\`](${sourceLink}) |`,
    );
  }

  lines.push(
    '',
    '## Automated test labs',
    '',
    'These fixtures are deterministic evidence for browser verification. Their visibility, maturity, action IDs, diagnostics, and manual procedures are intentionally test-oriented.',
    '',
    '| Order | Scenario | Category | Visibility / maturity | Lab route | Executable source |',
    '| ---: | --- | --- | --- | --- | --- |',
  );

  for (const entry of scenarioCatalogIndex.learningPath) {
    const metadata = entry.metadata;
    const sourceLink = `../${entry.source.path}`;
    lines.push(
      `| ${metadata.learningOrder} | <a id="${metadata.id}"></a>**${escapeCell(metadata.title)}**<br>${escapeCell(metadata.summary)} | ${escapeCell(metadata.category)} | ${metadata.visibility} / ${metadata.maturity} | \`${getScenarioRoute(entry)}\` | [\`${entry.source.path}\`](${sourceLink}) |`,
    );
  }

  lines.push(
    '',
    '## Test labs by public API',
    '',
    ...renderGroups(scenarioCatalogIndex.byApi),
    '',
    '## By concept',
    '',
    ...renderGroups(scenarioCatalogIndex.byConcept),
    '',
    '## By category',
    '',
    ...renderGroups(scenarioCatalogIndex.byCategory),
    '',
    '## By visibility and maturity',
    '',
    ...renderGroups(scenarioCatalogIndex.byVisibilityAndMaturity),
    '',
  );
  return `${lines.join('\n')}\n`;
}

async function validateSources(): Promise<void> {
  validateScenarioCatalog(scenarioCatalog);
  validateLearningExampleCatalog(learningExampleCatalog);
  validateTutorialSnapshotCatalog(tutorialSnapshotCatalog);
  const discoveredPaths = await discoverExampleSourcePaths(
    scenarioDirectory,
    workspaceRoot,
  );
  const catalogPaths = scenarioCatalog.map(entry => entry.source.path).sort();
  const learningCatalogPaths = learningExampleCatalog.map(entry => entry.source.path).sort();
  const tutorialCatalogPaths = tutorialSnapshotCatalog.map(entry => entry.source.path).sort();
  assertExampleSourceDiscovery(
    discoveredPaths,
    catalogPaths,
    learningCatalogPaths,
    tutorialCatalogPaths,
  );

  for (const entry of scenarioCatalog) {
    const sourceText = await readFile(resolve(workspaceRoot, entry.source.path), 'utf8');
    if (!entry.source.path.endsWith('.example.tsx')) {
      throw new Error(`Scenario "${entry.metadata.id}" must use a .example.tsx source path.`);
    }
    validateScenarioSourceText(sourceText, `Scenario "${entry.metadata.id}"`);
    if (!sourceText.includes(entry.source.marker)) {
      throw new Error(
        `Scenario "${entry.metadata.id}" source is missing marker "${entry.source.marker}".`,
      );
    }
    const definition = await loadScenario(entry);
    if (entry.metadata.visibility === 'documentation-candidate') {
      if (!sourceText.includes("from '@pibbl/core'")) {
        throw new Error(
          `Documentation candidate "${entry.metadata.id}" must show direct public @pibbl/core usage.`,
        );
      }
      if (/\b(?:describe|expect|it|test)\s*\(/u.test(sourceText) || sourceText.includes('vitest')) {
        throw new Error(
          `Documentation candidate "${entry.metadata.id}" contains test-runner diagnostics.`,
        );
      }
    }
    if (definition.actionIds.length !== entry.actions.length) {
      throw new Error(`Scenario "${entry.metadata.id}" has unreadable action metadata.`);
    }
  }

  for (const entry of learningExampleCatalog) {
    const sourceText = await readFile(resolve(workspaceRoot, entry.source.path), 'utf8');
    if (!entry.source.path.endsWith('.example.tsx')) {
      throw new Error(`Learning example "${entry.slug}" must use a .example.tsx source path.`);
    }
    validateLearningSourceText(sourceText, {
      authoring: entry.authoring,
      label: `Learning example "${entry.slug}"`,
      sourcePath: entry.source.path,
    });
    await loadLearningExample(entry);
  }

  for (const entry of tutorialSnapshotCatalog) {
    const sourceText = await readFile(resolve(workspaceRoot, entry.source.path), 'utf8');
    if (!entry.source.path.endsWith('.example.tsx')) {
      throw new Error(`Tutorial snapshot "${entry.slug}" must use a .example.tsx source path.`);
    }
    validateLearningSourceText(sourceText, {
      authoring: entry.authoring,
      label: `Tutorial snapshot "${entry.slug}"`,
      sourcePath: entry.source.path,
    });
    if (entry.chapter >= 4) {
      validateDiagramEditorTutorialSourceText(sourceText, {
        chapter: entry.chapter,
        label: `Tutorial snapshot "${entry.slug}"`,
      });
    }
    await loadTutorialSnapshot(entry);
  }
}

await validateSources();
const generatedIndex = await format(renderIndex(), { parser: 'markdown' });
if (process.argv.includes('--write')) {
  await writeFile(indexPath, generatedIndex, 'utf8');
  process.stdout.write(
    `Wrote ${relative(workspaceRoot, indexPath)} for ${learningExampleCatalog.length} lessons, ${tutorialSnapshotCatalog.length} tutorial snapshots, and ${scenarioCatalog.length} test labs.\n`,
  );
} else {
  const existingIndex = await readFile(indexPath, 'utf8').catch(() => '');
  if (existingIndex.replaceAll('\r\n', '\n') !== generatedIndex) {
    throw new Error('docs/scenario-index.md is stale. Run `pnpm scenarios:write-index`.');
  }
  process.stdout.write(
    `Validated ${learningExampleCatalog.length} lessons, ${tutorialSnapshotCatalog.length} tutorial snapshots, ${scenarioCatalog.length} test labs, and docs/scenario-index.md.\n`,
  );
}
