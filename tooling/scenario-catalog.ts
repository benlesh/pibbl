import {
  getScenarioRoute,
  loadScenario,
  scenarioCatalog,
  scenarioCatalogIndex,
  validateScenarioCatalog,
} from '@crc/scenarios';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { relative, resolve } from 'node:path';
import { format } from 'prettier';

const workspaceRoot = process.cwd();
const scenarioDirectory = resolve(workspaceRoot, 'packages/scenarios/src');
const indexPath = resolve(workspaceRoot, 'docs/scenario-index.md');

function displayList(values: readonly string[]): string {
  return values.length ? values.join(', ') : '(none)';
}

function escapeCell(value: string): string {
  return value.replaceAll('|', '\\|');
}

function scenarioLink(id: string, title: string): string {
  return `[${title}](#${id})`;
}

function renderGroups(
  groups: typeof scenarioCatalogIndex.byApi,
): string[] {
  return groups.map(group => {
    const links = group.scenarios.map(entry =>
      scenarioLink(entry.metadata.id, entry.metadata.title)
    );
    return `- **${group.label}:** ${links.join(', ')}`;
  });
}

function renderIndex(): string {
  const documentationCandidates = scenarioCatalog.filter(
    entry => entry.metadata.visibility === 'documentation-candidate',
  ).length;
  const lines = [
    '# Scenario index',
    '',
    '<!-- Generated by `pnpm scenarios:write-index`; do not edit by hand. -->',
    '',
    'This is the presentation-neutral index of CRC’s executable browser scenarios. ' +
      `It contains ${scenarioCatalog.length} cataloged scenarios: ${documentationCandidates} documentation candidates and ${scenarioCatalog.length - documentationCandidates} test laboratories.`,
    '',
    'Every entry below has one catalog record, one executable `*.example.ts` source, a stable gallery route, manual steps, expected results, and declared limitations. A future documentation renderer can project the documentation candidates without copying their code.',
    '',
    '## Learning path',
    '',
    '| Order | Scenario | Category | Visibility / maturity | Gallery route | Executable source |',
    '| ---: | --- | --- | --- | --- | --- |',
  ];

  for (const entry of scenarioCatalogIndex.learningPath) {
    const metadata = entry.metadata;
    const sourceLink = `../${entry.source.path}`;
    lines.push(
      `| ${metadata.learningOrder} | <a id="${metadata.id}"></a>**${escapeCell(metadata.title)}**<br>${escapeCell(metadata.summary)} | ${escapeCell(metadata.category)} | ${metadata.visibility} / ${metadata.maturity} | \`${getScenarioRoute(entry)}\` | [\`${entry.source.path}\`](${sourceLink}) |`,
    );
  }

  lines.push(
    '',
    '## By public API',
    '',
    ...renderGroups(scenarioCatalogIndex.byApi),
    '',
    '## By concept',
    '',
    ...renderGroups(scenarioCatalogIndex.byConcept),
    '',
    '## By category',
    '',
    ...renderGroups(scenarioCatalogIndex.byCategory),
    '',
    '## By visibility and maturity',
    '',
    ...renderGroups(scenarioCatalogIndex.byVisibilityAndMaturity),
    '',
  );
  return `${lines.join('\n')}\n`;
}

async function validateSources(): Promise<void> {
  validateScenarioCatalog(scenarioCatalog);
  const discoveredPaths = (await readdir(scenarioDirectory))
    .filter(name => name.endsWith('.example.ts'))
    .map(name => `packages/scenarios/src/${name}`)
    .sort();
  const catalogPaths = scenarioCatalog.map(entry => entry.source.path).sort();
  if (discoveredPaths.join('\n') !== catalogPaths.join('\n')) {
    const catalogSet = new Set(catalogPaths);
    const discoveredSet = new Set(discoveredPaths);
    const omitted = discoveredPaths.filter(path => !catalogSet.has(path));
    const missing = catalogPaths.filter(path => !discoveredSet.has(path));
    throw new Error(
      `Scenario source discovery disagrees with the catalog. Omitted: ${displayList(omitted)}. Missing: ${displayList(missing)}.`,
    );
  }

  for (const entry of scenarioCatalog) {
    const sourceText = await readFile(resolve(workspaceRoot, entry.source.path), 'utf8');
    if (!sourceText.includes(entry.source.marker)) {
      throw new Error(
        `Scenario "${entry.metadata.id}" source is missing marker "${entry.source.marker}".`,
      );
    }
    const definition = await loadScenario(entry);
    if (entry.metadata.visibility === 'documentation-candidate') {
      if (!sourceText.includes("from '@crc/core'")) {
        throw new Error(
          `Documentation candidate "${entry.metadata.id}" must show direct public @crc/core usage.`,
        );
      }
      if (/\b(?:describe|expect|it|test)\s*\(/u.test(sourceText) || sourceText.includes('vitest')) {
        throw new Error(
          `Documentation candidate "${entry.metadata.id}" contains test-runner diagnostics.`,
        );
      }
    }
    if (definition.actionIds.length !== entry.actions.length) {
      throw new Error(`Scenario "${entry.metadata.id}" has unreadable action metadata.`);
    }
  }
}

await validateSources();
const generatedIndex = await format(renderIndex(), { parser: 'markdown' });
if (process.argv.includes('--write')) {
  await writeFile(indexPath, generatedIndex, 'utf8');
  process.stdout.write(
    `Wrote ${relative(workspaceRoot, indexPath)} for ${scenarioCatalog.length} scenarios.\n`,
  );
} else {
  const existingIndex = await readFile(indexPath, 'utf8').catch(() => '');
  if (existingIndex !== generatedIndex) {
    throw new Error('docs/scenario-index.md is stale. Run `pnpm scenarios:write-index`.');
  }
  process.stdout.write(
    `Validated ${scenarioCatalog.length} scenarios and docs/scenario-index.md.\n`,
  );
}
