import { spawnSync } from "node:child_process";
import { createRequire } from "node:module";
import { mkdtemp, readFile, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
const root = new URL("../packages/core/", import.meta.url);
const require = createRequire(new URL("package.json", root));
const compiler = require.resolve("assemblyscript/bin/asc.js");
const temp = await mkdtemp(join(tmpdir(), "crc-transition-wasm-"));
try {
  for (const name of ["bifrost", "embers", "hologram"]) {
    const source = await readFile(
      new URL(`assembly/transitions/${name}.asc`, root),
      "utf8",
    );
    const input = join(temp, `${name}.ts`),
      output = join(temp, `${name}.wasm`);
    await writeFile(input, source);
    const result = spawnSync(
      process.execPath,
      [
        compiler,
        input,
        "--outFile",
        output,
        "--optimizeLevel",
        "3",
        "--shrinkLevel",
        "0",
        "--runtime",
        "stub",
        "--importMemory",
        "--initialMemory",
        "1",
        "--noAssert",
      ],
      { stdio: "inherit" },
    );
    if (result.status !== 0) throw new Error(`Failed compiling ${name}`);
    const bytes = await readFile(output);
    const text = `// Generated by tooling/build-transition-wasm.mjs; do not edit.\nexport const bytes = ${JSON.stringify(bytes.toString("base64"))};\n`;
    const destination = new URL(
      `src/lib/transitions/wasm/${name}-bytes.ts`,
      root,
    );
    if (process.argv.includes("--check")) {
      if ((await readFile(destination, "utf8")) !== text)
        throw new Error(
          `Stale ${name} kernel; run node tooling/build-transition-wasm.mjs`,
        );
    } else await writeFile(destination, text);
    console.warn(`${name}: ${bytes.length} bytes`);
  }
} finally {
  await rm(temp, { recursive: true, force: true });
}
