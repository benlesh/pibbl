import { spawnSync } from "node:child_process";
import { createRequire } from "node:module";
import { mkdtemp, readFile, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
const root = new URL("../packages/core/", import.meta.url);
const require = createRequire(new URL("package.json", root));
const compiler = require.resolve("assemblyscript/bin/asc.js");
const temp = await mkdtemp(join(tmpdir(), "crc-texture-wasm-"));
try {
  for (const [index, name] of [
    "marble",
    "paper",
    "cellular",
    "ink",
  ].entries()) {
    let source = await readFile(
      new URL(`assembly/textures/${name === "ink" ? "ink" : "materials"}.asc`, root),
      "utf8",
    );
    if (name !== "ink") {
      source = source
        .replace("function sample(", "@inline\nfunction sample(")
        .replace("export function generate(", "@inline\nfunction generate(");
      source += `\nexport function run(out: usize, w: i32, h: i32, seed: i32, scale: f64, detail: f64): void { generate(out,w,h,${index},seed,scale,detail); }\n`;
    }
    const input = join(temp, `${name}.ts`),
      output = join(temp, `${name}.wasm`);
    await writeFile(input, source);
    const result = spawnSync(
      process.execPath,
      [
        compiler,
        input,
        "--outFile",
        output,
        "--optimizeLevel",
        "3",
        "--shrinkLevel",
        "0",
        "--runtime",
        "stub",
        "--importMemory",
        "--initialMemory",
        "1",
        "--noAssert",
      ],
      { stdio: "inherit" },
    );
    if (result.status !== 0) throw new Error(`Failed compiling ${name}`);
    const bytes = await readFile(output);
    const text = `// Generated by tooling/build-texture-wasm.mjs; do not edit.\nexport const bytes = ${JSON.stringify(bytes.toString("base64"))};\n`;
    const destination = new URL(`src/features/textures/lib/wasm/${name}-bytes.ts`, root);
    if (process.argv.includes("--check")) {
      if ((await readFile(destination, "utf8")) !== text)
        throw new Error(`Stale ${name} kernel; run build:wasm`);
    } else await writeFile(destination, text);
    console.warn(`${name}: ${bytes.length} bytes`);
  }
} finally {
  await rm(temp, { recursive: true, force: true });
}
