import { spawnSync } from "node:child_process";
import { createRequire } from "node:module";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { tmpdir } from "node:os";

const root = new URL("../packages/core/", import.meta.url);
const require = createRequire(new URL("package.json", root));
const compiler = require.resolve("assemblyscript/bin/asc.js");
const temp = await mkdtemp(join(tmpdir(), "crc-water-surface-wasm-"));
try {
  const input = join(temp, "water-surface.ts");
  await writeFile(
    input,
    (await readFile(new URL("assembly/textures/water-modes.asc", root), "utf8")) +
      "\n" +
      (await readFile(new URL("assembly/textures/water-surface.asc", root), "utf8")),
  );
  const output = join(temp, "water-surface.wasm");
  const result = spawnSync(
    process.execPath,
    [
      compiler,
      input,
      "--outFile",
      output,
      "--optimizeLevel",
      "3",
      "--shrinkLevel",
      "0",
      "--runtime",
      "stub",
      "--importMemory",
      "--initialMemory",
      "1",
      "--noAssert",
    ],
    { stdio: "inherit" },
  );
  if (result.status !== 0) throw new Error("Failed compiling water-surface");
  const bytes = await readFile(output);
  const text = `// Generated by tooling/build-water-surface-wasm.mjs; do not edit.\nexport const bytes = ${JSON.stringify(bytes.toString("base64"))};\n`;
  const destination = new URL("src/features/textures/lib/wasm/water-surface-bytes.ts", root);
  if (process.argv.includes("--check")) {
    if ((await readFile(destination, "utf8")) !== text)
      throw new Error(
        "Stale water-surface kernel; run build:water-surface-wasm",
      );
  } else await writeFile(destination, text);
  console.warn(`water-surface: ${bytes.length} bytes`);
} finally {
  await rm(temp, { recursive: true, force: true });
}
