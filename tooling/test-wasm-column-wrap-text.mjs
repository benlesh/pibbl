import { strict as assert } from 'node:assert';
import { chromium } from 'playwright';
const base = process.argv[2] ?? 'http://127.0.0.1:5192';
const built = process.argv.includes('--built');
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${base}/#/examples/layout/wasm-flex-column-wrap`);
  const host = page.locator('iframe[srcdoc]');
  await host.waitFor({ state: 'attached' });
  await host.scrollIntoViewIfNeeded();
  const frame = page.frameLocator('iframe[srcdoc]');
  await frame.locator('pre').waitFor();
  const sandbox = page.frames().find(value => value.url() === 'about:srcdoc');
  const read = async () => JSON.parse(await frame.locator('pre').innerText());
  const click = async (x,y) => {
    const bounds = await frame.locator('canvas').boundingBox();
    const scale = Math.min(bounds.width/760,bounds.height/460);
    await frame.locator('canvas').click({position:{x:(bounds.width-760*scale)/2+x*scale,y:(bounds.height-460*scale)/2+y*scale}});
    await page.waitForTimeout(240);
  };
  const initial = await read();
  assert.equal(initial.height,288);
  await click(640,118);
  const short = await read();
  assert.equal(short.measuredText,true);
  assert.deepEqual(short.stamps,initial.stamps);
  assert.deepEqual(short.boxes,{A:{x:28,y:178,width:192,height:84},B:{x:232,y:148,width:192,height:84},C:{x:232,y:244,width:192,height:84}});
  await click(33,183);
  assert.equal((await read()).hits,1);
  await click(236,118);
  const long = await read();
  assert.deepEqual(long.boxes,{A:{x:232,y:148,width:192,height:84},B:{x:232,y:244,width:192,height:84},C:{x:436,y:148,width:192,height:84}});
  assert.deepEqual(long.stamps,short.stamps);
  await click(33,183);
  assert.equal((await read()).hits,1);
  await click(237,153);
  assert.equal((await read()).hits,2);
  const beforePaint = await read();
  await click(432,118);
  const painted = await read();
  assert.deepEqual(painted.boxes,long.boxes);
  for(const key of ['measuredLeaves','solves','lineFormations','nodeCreates']) assert.equal(painted.layout[key],beforePaint.layout[key],key);
  await click(60,118);
  const resized = await read();
  assert.deepEqual(resized.boxes,{A:{x:28,y:304,width:192,height:84},B:{x:232,y:148,width:192,height:84},C:{x:232,y:244,width:192,height:84}});
  assert.equal(resized.layout.measuredLeaves,painted.layout.measuredLeaves);
  assert.deepEqual(resized.stamps,short.stamps);
  await click(33,309);
  assert.equal((await read()).hits,3);
  const proof = await sandbox.evaluate(() => globalThis.__PIBBL_BUILT_LAYOUT_PROOF__);
  if(built){assert.equal(proof?.mode,'layout-wasm-built');assert.ok(proof.coreInputs.length && proof.coreInputs.every(value=>value.includes('packages/core/.layout-wasm-package/dist/')));}
  const disposed = await sandbox.evaluate(()=>{dispatchEvent(new PageTransitionEvent('pagehide'));return globalThis.__PIBBL_LAYOUT_DIAGNOSTICS__();});
  assert.deepEqual([disposed.activeNodes,disposed.activeArenas,disposed.cachedMeasurements],[0,0,0]);
  assert.deepEqual(errors,[]);
  console.warn(JSON.stringify({base,short:short.boxes,long:long.boxes,resized:resized.boxes,stamps:short.stamps,builtInputs:proof?.coreInputs.length??null,cleanup:[0,0,0],errors}));
} finally {await browser.close();}
