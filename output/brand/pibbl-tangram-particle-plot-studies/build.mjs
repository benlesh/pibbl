import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const sharp=require(process.env.PIBBL_SHARP_PATH||'sharp');
const dir=path.dirname(fileURLToPath(import.meta.url));
const identity=JSON.parse(await fs.readFile(path.join(dir,'../pibbl-tangram/source/identity.json'),'utf8'));
const glyphs=JSON.parse(await fs.readFile(path.join(dir,'../pibbl-tangram/source/wordmark-paths.json'),'utf8'));
const colors=['#FF735E','#159447','#8B5CCB'];
const ink='#111211';
const esc=s=>s.replaceAll('&','&amp;');
const svg=(w,h,body,title)=>`<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" role="img"><title>${esc(title)}</title>${body}</svg>`;
const base=identity.icon.map((s,i)=>`<path d="${s.d}" fill="${colors[i]}"/>`).join('');
const word=`<g transform="translate(360 73)" fill="${ink}">${glyphs.map(g=>`<path d="${g.d}" fill-rule="${g.rule||'nonzero'}"/>`).join('')}</g>`;
const logo=mark=>`<g transform="translate(35 35)">${mark}</g>${word}`;
const dot=(x,y,r,color)=>`<circle cx="${x}" cy="${y}" r="${r}" fill="${color}"/>`;
const line=(d,color,width=3,extra='')=>`<path d="${d}" fill="none" stroke="${color}" stroke-width="${width}" stroke-linecap="round" stroke-linejoin="round" ${extra}/>`;
const clip=(id,d,body)=>`<defs><clipPath id="${id}"><path d="${d}"/></clipPath></defs><g clip-path="url(#${id})">${body}</g>`;
const violet=colors[2],green=colors[1],coral=colors[0],guide='#CDB8E9';
const holes=[[211,20,7],[223,43,6],[225,68,7],[215,97,6],[198,120,4]];
const bloom=id=>base.replace(`<path d="${identity.icon[2].d}" fill="${violet}"/>`,`<defs><mask id="${id}" maskUnits="userSpaceOnUse" x="128" y="0" width="130" height="145"><rect x="128" y="0" width="130" height="145" fill="white"/>${holes.map(([x,y,r])=>dot(x,y,r,'black')).join('')}</mask></defs><path d="${identity.icon[2].d}" fill="${violet}" mask="url(#${id})"/>`);
const dots=points=>points.map(([x,y,r,c=violet])=>dot(x,y,r,c)).join('');
const variants=[];
let scatter=line('M235 17V132H309',guide,2);
for(const y of [40,70,100])scatter+=line(`M235 ${y}H309`,guide,1,'opacity=".45"');
scatter+=dots([[235,30,6],[249,55,4,coral],[242,88,6],[268,76,5,green],[260,109,4],[281,45,6],[296,24,4,green],[298,92,3,coral]]);
variants.push(['Scatter bloom','Particles become observations on a tiny scatter plot.',bloom('scatter')+scatter]);
let trend=line('M235 25V133H309',guide,2)+line('M229 104L251 78L276 83L302 37',violet,3);
trend+=line('M177 119L199 111L216 116','white',3);
trend+=dots([[229,104,6],[251,78,6,green],[276,83,6],[302,37,7,coral],[240,40,3],[286,114,3,green]]);
variants.push(['Rising signal','A loose particle trail resolves into a rising line chart.',bloom('trend')+trend]);
let bubbles=line('M237 16V133H311',guide,2);
bubbles+=dots([[236,25,4],[240,68,7],[251,105,5],[269,42,11,green],[289,96,13],[304,24,6,coral],[298,62,4,green]]);
variants.push(['Bubble field','Different dot sizes turn the bloom into a bubble chart.',bloom('bubble')+bubbles]);
let trianglePlot=line('M38 122H111V42',guide,2)+line('M48 112L70 104L91 81L110 57',violet,2.5);
trianglePlot+=dots([[48,112,4,coral],[70,104,4,green],[91,81,4],[110,57,4]]);
trianglePlot+=dots([[237,27,5],[251,50,4,coral],[244,80,6],[266,106,3,green],[271,28,3],[283,65,4,green]]);
variants.push(['Chart in the gap','A plotted line in the triangle pairs with a free particle bloom.',bloom('gap')+trianglePlot]);
let matrix='';
for(let col=0;col<5;col++)for(let row=0;row<5;row++){
 if(col+row===7||col===4&&row===0)continue;
 const x=221+col*19,y=22+row*23;
 const r=col===0?4.5:col===1?5:col===2?4:col===3?3:2.5;
 const c=(col===3&&row===1)||(col===4&&row===3)?green:(col===2&&row===4)?coral:violet;
 matrix+=dot(x,y,r,c);
}
variants.push(['Ordered bloom','A dissolving curve settles into a grid of data points.',bloom('matrix')+matrix]);
let radial=line('M226 21A54 54 0 0 1 248 111',guide,2)+line('M249 8A76 76 0 0 1 271 128',guide,2);
radial+=line('M232 70H303',guide,1.5,'stroke-dasharray="3 6"');
radial+=dots([[238,38,6],[248,70,5,green],[236,108,4],[268,30,6,coral],[289,67,7],[276,112,5],[302,93,3,green]]);
variants.push(['Orbital plot','Particles follow radial guides around the curved bowl.',bloom('radial')+radial]);
let board=`<rect width="1800" height="1410" fill="#F4F3EF"/><g font-family="Arial,Helvetica,sans-serif" fill="${ink}"><text x="48" y="55" font-size="32" font-weight="bold">Pibbl · Particles become data</text><text x="48" y="92" font-size="20">Six variations on Particle bloom · Vivid coral + Kelly green + soft violet</text></g>`;
for(let i=0;i<variants.length;i++){
 const [name,caption,mark]=variants[i];
 const filename=`${String(i+1).padStart(2,'0')}-${name.toLowerCase().replace(/[^a-z]+/g,'-')}`;
 const s=svg(947,364,logo(mark),'Pibbl — '+name);
 await fs.writeFile(path.join(dir,filename+'.svg'),s);
 await sharp(Buffer.from(s)).resize(1894,728).png().toFile(path.join(dir,filename+'.png'));
 const icon=svg(390,350,`<g transform="translate(35 35)">${mark}</g>`,'Pibbl '+name+' icon');
 await fs.writeFile(path.join(dir,filename+'-icon.svg'),icon);
 await sharp(Buffer.from(icon)).resize(780,700).png().toFile(path.join(dir,filename+'-icon.png'));
 const x=48+i%2*864,y=126+Math.floor(i/2)*420;
 board+=`<rect x="${x}" y="${y}" width="840" height="395" rx="12" fill="white"/><g transform="translate(${x+48} ${y+27}) scale(.78)">${logo(mark)}</g><g font-family="Arial,Helvetica,sans-serif" fill="${ink}"><text x="${x+28}" y="${y+320}" font-size="24" font-weight="bold">${i+1}. ${name}</text><text x="${x+28}" y="${y+356}" font-size="18">${caption}</text></g>`;
}
const sheet=svg(1800,1410,board,'Pibbl particle and chart logo explorations');
await fs.writeFile(path.join(dir,'comparison.svg'),sheet);
await sharp(Buffer.from(sheet)).png().toFile(path.join(dir,'comparison.png'));
console.log('Created six particle/plot logo studies, with SVG and PNG lockups and icons.');
